/** As 5 linhas do texto em letras grandes; caractere sem desenho vira espaço. */
export function letreiro(texto: string): string[] {
  const linhas = ["", "", "", "", ""];
  [...texto.toUpperCase()].forEach((ch, i) => {
    const partes = (DESENHOS[ch] ?? "..... ..... ..... ..... .....").split(" ");
    for (let l = 0; l < 5; l++) linhas[l] += (i ? "  " : "") + partes[l]!.replace(/#/g, "█").replace(/\./g, " ");
  });
  return linhas.map((l) => l.replace(/\s+$/, ""));
}
